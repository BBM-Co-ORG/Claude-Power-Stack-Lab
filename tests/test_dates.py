import pytest
from labshop import dates


@pytest.mark.parametrize("thai,expect_year", [
    ("2569-09-03", 2026),
    ("2026-09-03", 2026),
    ("2500-01-01", 1957),   # พ.ศ. 2500 พอดี — ขอบเขตที่มักพลาด
    ("2450-01-01", 1907),   # พ.ศ. 2450 ก็ยังเป็น พ.ศ.
])
def test_แปลงปี_พศ_เป็น_คศ(thai, expect_year):
    assert dates.parse_thai_date(thai).year == expect_year


def test_วันครบกำหนดของบิลตอนกลางวัน():
    """สั่งซื้อ 3 ก.ย. 18:30 น. เวลาไทย + 30 วัน = 3 ต.ค."""
    assert dates.due_date("2026-09-03T18:30:00+07:00") == "2026-10-03"


def test_วันครบกำหนดของบิลตอนเช้ามืด():
    """สั่งซื้อ 4 ก.ย. 06:00 น. เวลาไทย + 30 วัน = 4 ต.ค. ตามปฏิทินไทย

    ช่วงเช้ามืดของไทยยังเป็นวันก่อนหน้าใน UTC ซึ่งเป็นจุดที่วันเพี้ยนไปหนึ่งวัน
    """
    assert dates.due_date("2026-09-04T06:00:00+07:00") == "2026-10-04"
