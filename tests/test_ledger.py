from labshop import ledger


def test_ยอดค้างชำระของลูกค้ารายเดียว():
    ledger.post("ห้างหุ้นส่วน สยามเทค", 46705.50)
    assert ledger.balance_for("ห้างหุ้นส่วน สยามเทค") == 46705.50


def test_ลูกค้ารายเดิมยอดเท่าเดิมเมื่อเริ่มเทสใหม่():
    """เทสนี้ผ่านเมื่อรันเดี่ยว แต่ไม่ผ่านเมื่อรันต่อจากเทสข้างบนในกระบวนการเดียวกัน

    รันเดี่ยวด้วย: pytest tests/test_ledger.py::test_ลูกค้ารายเดิมยอดเท่าเดิมเมื่อเริ่มเทสใหม่
    """
    ledger.post("ห้างหุ้นส่วน สยามเทค", 46705.50)
    assert ledger.balance_for("ห้างหุ้นส่วน สยามเทค") == 46705.50
